import assert from 'node:assert/strict';
import {readFile,writeFile,mkdtemp,mkdir} from 'node:fs/promises';
import {createServer} from 'node:http';
import {spawn} from 'node:child_process';
import {tmpdir} from 'node:os';
import {join,resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const html=await readFile(join(root,'preview/index.html'));
const server=createServer((request,response)=>{response.setHeader('Content-Type','text/html; charset=utf-8');response.end(html);});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const url=`http://127.0.0.1:${server.address().port}/`;
const profile=await mkdtemp(join(tmpdir(),'classic-browser-'));
const chrome=spawn('/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',['--headless=new','--disable-gpu','--no-first-run','--no-default-browser-check','--disable-background-networking','--remote-debugging-port=0',`--user-data-dir=${profile}`,'--window-size=1600,1000',url],{stdio:'ignore'});
const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
let socket;
let send;
const checked=[];
try{
 let port;
 for(let i=0;i<120;i++){try{port=(await readFile(join(profile,'DevToolsActivePort'),'utf8')).split('\n')[0];break;}catch{await pause(50);}}
 assert.ok(port,'Isolated browser started');
 const pages=await(await fetch(`http://127.0.0.1:${port}/json/list`)).json();
 socket=new WebSocket(pages.find(page=>page.type==='page').webSocketDebuggerUrl);
 await new Promise((resolve,reject)=>{socket.onopen=resolve;socket.onerror=reject;});
 let serial=0;const pending=new Map();
 socket.onmessage=event=>{const result=JSON.parse(event.data);if(!result.id)return;const task=pending.get(result.id);pending.delete(result.id);result.error?task.reject(Error(JSON.stringify(result.error))):task.resolve(result.result);};
 send=(method,params={})=>new Promise((resolve,reject)=>{const id=++serial;pending.set(id,{resolve,reject});socket.send(JSON.stringify({id,method,params}));});
 const evaluate=async expression=>{const result=await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(result.exceptionDetails)throw Error(result.exceptionDetails.exception?.description||result.exceptionDetails.text);return result.result.value;};
 async function until(expression){for(let i=0;i<150;i++){if(await evaluate(expression))return;await pause(30);}throw Error(`Timed out: ${expression}`);}
 await send('Runtime.enable');await send('Page.enable');
 await until('!!window.previewReady');await evaluate('window.previewReady');
 assert.equal(await evaluate("getComputedStyle(el('history')).backgroundImage"),'none');
 assert.equal(await evaluate("getComputedStyle(el('history')).backgroundColor"),'rgb(192, 192, 192)');
 checked.push('Initial chat background is classic solid gray');
 await send('Emulation.setDeviceMetricsOverride',{width:1600,height:1000,deviceScaleFactor:1,mobile:false});
 const initial=await send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
 await writeFile(join(root,'evidence/classic-preview.png'),Buffer.from(initial.data,'base64'));
 await evaluate("el('settings').click()");assert.equal(await evaluate("el('dialog-overlay').hidden"),false);
 const document=await send('DOM.getDocument');const input=await send('DOM.querySelector',{nodeId:document.root.nodeId,selector:'#background-file'});
 await send('DOM.setFileInputFiles',{nodeId:input.nodeId,files:[join(root,'evidence/test-wallpaper.png')]});
 await until("state.visible && !!state.blob && getComputedStyle(el('history')).backgroundImage.includes('blob:')");
 await until("read().then(value=>!!value?.blob && value.visible)");
 checked.push('Selecting a real local PNG enables and saves wallpaper');
 await evaluate("el('background-fit').value='tile';el('background-fit').dispatchEvent(new Event('change'))");
 await until("read().then(value=>value?.fit==='tile')");assert.equal(await evaluate("el('history').dataset.fit"),'tile');
 checked.push('Wallpaper placement is persisted');
 await evaluate("el('background-visible').click()");
 await until("read().then(value=>value?.visible===false && !!value.blob)");
 assert.equal(await evaluate("getComputedStyle(el('history')).backgroundImage"),'none');
 checked.push('Hiding wallpaper keeps its stored image');
 await send('Page.reload');await pause(120);await until('!!window.previewReady');await evaluate('window.previewReady');
 assert.equal(await evaluate('state.visible'),false);assert.equal(await evaluate('!!state.blob'),true);
 await evaluate("el('settings').click();el('background-visible').click()");
 await until("state.visible && getComputedStyle(el('history')).backgroundImage.includes('blob:')");
 checked.push('Restart preserves hidden wallpaper and the switch restores it');
 await evaluate("el('background-fit').value='cover';el('background-fit').dispatchEvent(new Event('change'));el('dialog-close').click()");
 const wallpaperShot=await send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false});
 await writeFile(join(root,'evidence/classic-wallpaper-preview.png'),Buffer.from(wallpaperShot.data,'base64'));
 await evaluate("el('settings').click();el('remove-background').click()");
 await until("read().then(value=>value?.blob===null && value.visible===false)");
 await send('Page.reload');await pause(120);await until('!!window.previewReady');await evaluate('window.previewReady');
 assert.equal(await evaluate('!!state.blob'),false);
 checked.push('Removing wallpaper clears the image across reloads');
 await evaluate("el('settings').click()");
 await send('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27});
 assert.equal(await evaluate("el('dialog-overlay').hidden"),true);
 assert.equal(await evaluate('document.activeElement.id'),'settings');
 checked.push('Dialog closes with Escape and returns keyboard focus');
 await evaluate("el('message').value='<img src=x onerror=alert(1)>';el('composer').requestSubmit()");
 assert.equal(await evaluate("el('history').querySelectorAll('img').length"),0);
 checked.push('Preview messages render safely as text');
 await evaluate("el('search-field').value='Семья';el('search-field').dispatchEvent(new Event('input'))");
 assert.equal(await evaluate("[...document.querySelectorAll('.chat-row')].filter(row=>!row.hidden).length"),1);
 checked.push('Chat filtering works');
 for(const width of [1600,800,400]){
  await send('Emulation.setDeviceMetricsOverride',{width,height:900,deviceScaleFactor:1,mobile:false});await pause(50);
  assert.equal(await evaluate('document.documentElement.scrollWidth<=window.innerWidth'),true,`No horizontal page overflow at ${width}`);
 }
 checked.push('Layout fits 1600, 800 and 400 pixels');
 await writeFile(join(root,'evidence/preview-checks.json'),JSON.stringify({status:'passed',scope:'HTML design preview, not a native Telegram build',checks:checked},null,2)+'\n');
 console.log(JSON.stringify({status:'passed',checks:checked},null,2));
}catch(error){console.error(error);process.exitCode=1;}finally{socket?.close();chrome.kill();server.close();}
